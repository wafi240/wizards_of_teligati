-- 1. Extend Projects Table (Research Opportunities)
ALTER TABLE projects ADD COLUMN IF NOT EXISTS positions_count INTEGER DEFAULT 1 NOT NULL;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS deadline TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS preferred_background VARCHAR(255);
ALTER TABLE projects ADD COLUMN IF NOT EXISTS eligibility_criteria TEXT;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS duration VARCHAR(100);
ALTER TABLE projects ADD COLUMN IF NOT EXISTS skills_required VARCHAR(255);
ALTER TABLE projects ADD COLUMN IF NOT EXISTS category VARCHAR(100) DEFAULT 'COMPUTER_SCIENCE' NOT NULL;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS min_cgpa DOUBLE PRECISION;

CREATE INDEX IF NOT EXISTS idx_projects_category ON projects (category);
CREATE INDEX IF NOT EXISTS idx_projects_deadline ON projects (deadline);

-- 2. Create Research Papers Table
CREATE TABLE IF NOT EXISTS research_papers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    abstract_text TEXT NOT NULL,
    research_field VARCHAR(100) NOT NULL,
    authors VARCHAR(255) NOT NULL,
    publication_date VARCHAR(50),
    doi VARCHAR(255),
    reference_url VARCHAR(500),
    attachment_url VARCHAR(500),
    teacher_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_research_papers_teacher FOREIGN KEY (teacher_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_research_papers_teacher ON research_papers (teacher_id);
CREATE INDEX IF NOT EXISTS idx_research_papers_field ON research_papers (research_field);
CREATE INDEX IF NOT EXISTS idx_research_papers_created ON research_papers (created_at);

-- 3. Extend Applications Table with Revision & Review Feedback
ALTER TABLE applications ADD COLUMN IF NOT EXISTS feedback TEXT;
ALTER TABLE applications ADD COLUMN IF NOT EXISTS review_notes TEXT;

-- 4. Create Notifications Table for Backend-Generated Academic Events
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    type VARCHAR(50),
    reference_id VARCHAR(100),
    is_read BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications (user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_created ON notifications (created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_is_read ON notifications (is_read);
