-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255),
    role VARCHAR(50),
    is_verified BOOLEAN DEFAULT FALSE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

-- 2. Profiles Table
CREATE TABLE IF NOT EXISTS profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    roll VARCHAR(50),
    department VARCHAR(50),
    batch VARCHAR(50),
    graduation_year VARCHAR(50),
    status VARCHAR(50),
    current_company VARCHAR(100),
    current_position VARCHAR(100),
    country VARCHAR(50),
    city VARCHAR(50),
    is_available_for_mentorship BOOLEAN DEFAULT FALSE NOT NULL,
    user_id BIGINT UNIQUE,
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_profiles_roll ON profiles (roll);
CREATE INDEX IF NOT EXISTS idx_profiles_user_id ON profiles (user_id);

-- 3. Jobs Table
CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150),
    company VARCHAR(100),
    location VARCHAR(100),
    type VARCHAR(50),
    description TEXT,
    compensation VARCHAR(100),
    posted_by_id BIGINT,
    CONSTRAINT fk_jobs_posted_by FOREIGN KEY (posted_by_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_jobs_posted_by_id ON jobs (posted_by_id);

-- 4. Projects Table
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150),
    description TEXT,
    technologies VARCHAR(255),
    github_url VARCHAR(255),
    is_open_for_contribution BOOLEAN DEFAULT TRUE NOT NULL,
    owner_id BIGINT,
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_projects_owner_id ON projects (owner_id);

-- 5. Transactions Table
CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(100) UNIQUE,
    amount NUMERIC(12, 2),
    type VARCHAR(50),
    status VARCHAR(50),
    timestamp TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    user_id BIGINT,
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_transactions_user_id ON transactions (user_id);
