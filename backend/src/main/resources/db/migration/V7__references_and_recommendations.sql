CREATE TABLE IF NOT EXISTS reference_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    recipient_role VARCHAR(50) NOT NULL,
    purpose VARCHAR(100) NOT NULL,
    target_institution VARCHAR(255) NOT NULL,
    target_program VARCHAR(255),
    deadline TIMESTAMP WITHOUT TIME ZONE,
    personal_message TEXT NOT NULL,
    supporting_info TEXT,
    status VARCHAR(50) DEFAULT 'PENDING' NOT NULL,
    recommendation_text TEXT,
    response_notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_reference_requests_student FOREIGN KEY (student_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reference_requests_recipient FOREIGN KEY (recipient_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_reference_requests_student ON reference_requests (student_id);
CREATE INDEX IF NOT EXISTS idx_reference_requests_recipient ON reference_requests (recipient_id);
CREATE INDEX IF NOT EXISTS idx_reference_requests_status ON reference_requests (status);
CREATE INDEX IF NOT EXISTS idx_reference_requests_created ON reference_requests (created_at);
