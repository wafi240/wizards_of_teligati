-- 1. Create Wallets Table (Simulated Demo Credits)
CREATE TABLE IF NOT EXISTS wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    available_balance NUMERIC(12, 2) DEFAULT 10000.00 NOT NULL,
    escrow_balance NUMERIC(12, 2) DEFAULT 0.00 NOT NULL,
    currency VARCHAR(20) DEFAULT 'DEMO_CREDITS' NOT NULL,
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_available_balance_non_negative CHECK (available_balance >= 0.00),
    CONSTRAINT chk_escrow_balance_non_negative CHECK (escrow_balance >= 0.00)
);

CREATE INDEX IF NOT EXISTS idx_wallets_user_id ON wallets (user_id);

-- 2. Create Escrows Table (Simulated Demo Escrow Contracts)
CREATE TABLE IF NOT EXISTS escrows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrow_reference VARCHAR(100) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(50) DEFAULT 'CREATED' NOT NULL, -- CREATED, FUNDED, IN_PROGRESS, RELEASED, REFUNDED, CANCELLED, DISPUTED
    payer_id BIGINT NOT NULL,
    payee_id BIGINT NOT NULL,
    job_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_escrows_payer FOREIGN KEY (payer_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_escrows_payee FOREIGN KEY (payee_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_escrows_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE SET NULL,
    CONSTRAINT chk_escrow_amount_positive CHECK (amount > 0.00)
);

CREATE INDEX IF NOT EXISTS idx_escrows_payer_id ON escrows (payer_id);
CREATE INDEX IF NOT EXISTS idx_escrows_payee_id ON escrows (payee_id);
CREATE INDEX IF NOT EXISTS idx_escrows_status ON escrows (status);
CREATE INDEX IF NOT EXISTS idx_escrows_reference ON escrows (escrow_reference);

-- 3. Extend Transactions Table
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS title VARCHAR(255);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS category VARCHAR(100);
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS escrow_id BIGINT;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS completed_at TIMESTAMP WITHOUT TIME ZONE;

-- Add foreign key constraint to escrow
ALTER TABLE transactions ADD CONSTRAINT fk_transactions_escrow
    FOREIGN KEY (escrow_id) REFERENCES escrows (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_transactions_escrow_id ON transactions (escrow_id);
CREATE INDEX IF NOT EXISTS idx_transactions_type ON transactions (type);
CREATE INDEX IF NOT EXISTS idx_transactions_status ON transactions (status);
